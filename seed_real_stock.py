def main():
    if not os.path.exists(DB_PATH):
        raise FileNotFoundError(f"ไม่พบฐานข้อมูล: {DB_PATH}")

    db = sqlite3.connect(DB_PATH)
    db.execute("PRAGMA foreign_keys = ON")

    sql = """
        INSERT OR REPLACE INTO items
            (code, name, unit, category, opening, received, used, ending, par, status, location, created_at)
        VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 'Main Store', ?)
    """
    now = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    rows = [(*row, now) for row in ITEMS]

    db.executemany(sql, rows)
    db.commit()

    total = db.execute("SELECT COUNT(*) FROM items").fetchone()[0]
    cafe = db.execute("SELECT COUNT(*) FROM items WHERE category='cafe'").fetchone()[0]
    kitchen = db.execute("SELECT COUNT(*) FROM items WHERE category='kitchen'").fetchone()[0]
    db.close()
    print(f"Seed เรียบร้อยครับ")
    print(f"   รวม {total} รายการ (Cafe: {cafe}, Kitchen: {kitchen})")

if __name__ == "__main__":
    main()
